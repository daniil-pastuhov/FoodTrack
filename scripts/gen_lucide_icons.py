#!/usr/bin/env python3
"""Generates the Android Lucide icons and empty-state art from the design spec.

    curl -sSfL https://registry.npmjs.org/lucide-static/-/lucide-static-0.460.0.tgz | tar xz -C /tmp
    scripts/gen_lucide_icons.py /tmp/package/icons

Icon names come from the design itself: the list on docs/design/src/pages/system.html plus every
data-icon in docs/design/src/pages/*.html, and EXTRA_ICONS for any the design doesn't draw. Writes
one vector drawable per icon at the tokens.json stroke width, the LarderIcons enum, and
LarderArtData.kt (art.svg.html as path data, because the art takes its colours from the Compose
theme, which a night-qualified resource can't follow when the user forces light or dark).
Never edit the outputs by hand: change the spec and run this again.
"""
import json
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DESIGN = ROOT / "docs/design"
DRAWABLES = ROOT / "androidApp/src/main/res/drawable"
KOTLIN = ROOT / "androidApp/src/main/java/com/foodtracker/android/ui/design"
HEADER = "Generated by scripts/gen_lucide_icons.py. Do not edit."
STROKE = json.loads((DESIGN / "tokens.json").read_text())["icons"]["stroke"]
EXTRA_ICONS = []


def num(value):
    return f"{float(value):g}"


def rounded_rect(x, y, w, h, rx, ry):
    if rx == 0 and ry == 0:
        return f"M{num(x)} {num(y)}h{num(w)}v{num(h)}h{num(-w)}z"

    def arc(dx, dy):
        return f"a{num(rx)} {num(ry)} 0 0 1 {num(dx)} {num(dy)}"

    return (f"M{num(x + rx)} {num(y)}h{num(w - 2 * rx)}{arc(rx, ry)}v{num(h - 2 * ry)}{arc(-rx, ry)}"
            f"h{num(2 * rx - w)}{arc(-rx, -ry)}v{num(2 * ry - h)}{arc(rx, -ry)}z")


def ellipse(cx, cy, rx, ry):
    return (f"M{num(cx - rx)} {num(cy)}a{num(rx)} {num(ry)} 0 1 0 {num(2 * rx)} 0"
            f"a{num(rx)} {num(ry)} 0 1 0 {num(-2 * rx)} 0z")


def to_path(element):
    """One SVG shape as path data: vector drawables only know paths."""
    tag = element.tag.rsplit("}", 1)[-1]

    def get(name):
        return float(element.get(name, 0))

    if tag == "path":
        return element.get("d")
    if tag == "circle":
        return ellipse(get("cx"), get("cy"), get("r"), get("r"))
    if tag == "ellipse":
        return ellipse(get("cx"), get("cy"), get("rx"), get("ry"))
    if tag == "line":
        return f"M{num(get('x1'))} {num(get('y1'))}L{num(get('x2'))} {num(get('y2'))}"
    if tag in ("polyline", "polygon"):
        points = re.findall(r"-?[\d.]+", element.get("points"))
        pairs = [f"{num(points[i])} {num(points[i + 1])}" for i in range(0, len(points), 2)]
        return "M" + "L".join(pairs) + ("z" if tag == "polygon" else "")
    if tag == "rect":
        rx = element.get("rx", element.get("ry", 0))
        ry = element.get("ry", rx)
        return rounded_rect(get("x"), get("y"), get("width"), get("height"), float(rx), float(ry))
    raise ValueError(f"Unsupported SVG element <{tag}>")


def icon_names():
    pages = DESIGN / "src/pages"
    names = set(EXTRA_ICONS)
    system = (pages / "system.html").read_text()
    names.update(re.search(r'data-render="icons" data-names="([^"]+)"', system)[1].split(","))
    for page in pages.glob("*.html"):
        names.update(re.findall(r'data-icon="([a-z0-9-]+)"', page.read_text()))
    return sorted(names)


def pascal(name):
    return "".join(part.capitalize() for part in name.split("-"))


def write_icon(name, source):
    svg = ET.parse(source / f"{name}.svg").getroot()
    # One <path> per shape: Lucide's paths can start with a relative moveto, which would land
    # somewhere else if they were joined into one.
    paths = "".join(
        f'    <path\n        android:pathData="{to_path(child)}"\n'
        '        android:strokeColor="#FF000000"\n'
        f'        android:strokeWidth="{STROKE}"\n'
        '        android:strokeLineCap="round"\n        android:strokeLineJoin="round" />\n'
        for child in svg)
    (DRAWABLES / f"lucide_{name.replace('-', '_')}.xml").write_text(
        f'<?xml version="1.0" encoding="utf-8"?>\n<!-- {HEADER} Lucide {name}, ISC licence. -->\n'
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="24dp"\n    android:height="24dp"\n'
        '    android:viewportWidth="24"\n    android:viewportHeight="24">\n'
        f'{paths}</vector>\n')


def write_enum(names):
    entries = "\n".join(f"    {pascal(n)}(R.drawable.lucide_{n.replace('-', '_')})," for n in names)
    (KOTLIN / "LarderIcons.kt").write_text(
        f"// {HEADER}\npackage com.foodtracker.android.ui.design\n\n"
        "import androidx.annotation.DrawableRes\nimport com.foodtracker.android.R\n\n"
        "/** Every Lucide icon in the design. Draw one with [LarderIcon]. */\n"
        f"enum class LarderIcons(@DrawableRes val res: Int) {{\n{entries}\n}}\n")


def write_art():
    source = (DESIGN / "src/art.svg.html").read_text()
    source = source[source.index("<defs>") + 6:source.index("</defs>")]
    blocks = []
    for symbol in re.finditer(r'<symbol id="art-(\w+)"[^>]*>(.*?)</symbol>', source, re.S):
        root = ET.fromstring(f"<g>{symbol[2]}</g>")
        layers = []
        for child in root:
            paint = {"art-a": "Accent", "art-b": "Soft", "art-l": "Line"}[child.get("class")]
            layers.append(f'            LarderArtLayer(LarderArtPaint.{paint}, "{to_path(child)}"),')
        blocks.append(f"    {symbol[1].capitalize()}(\n        listOf(\n"
                      + "\n".join(layers) + "\n        )\n    ),")
    (KOTLIN / "LarderArtData.kt").write_text(
        f"// {HEADER}\npackage com.foodtracker.android.ui.design\n\n"
        "internal enum class LarderArtPaint { Accent, Soft, Line }\n\n"
        "internal data class LarderArtLayer(val paint: LarderArtPaint, val pathData: String)\n\n"
        "/** Empty-state illustrations on a 160 by 120 canvas. Draw one with [LarderIllustration]. */\n"
        "enum class LarderArt(internal val layers: List<LarderArtLayer>) {\n"
        + "\n".join(blocks) + "\n}\n")


def main():
    source = Path(sys.argv[1])
    KOTLIN.mkdir(parents=True, exist_ok=True)
    names = icon_names()
    for stale in DRAWABLES.glob("lucide_*.xml"):
        stale.unlink()
    for name in names:
        write_icon(name, source)
    write_enum(names)
    write_art()
    print(f"{len(names)} icons")


if __name__ == "__main__":
    main()
