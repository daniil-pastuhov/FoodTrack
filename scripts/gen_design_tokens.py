#!/usr/bin/env python3
"""Generates the apps' design tokens from docs/design/tokens.json, so they can't drift.

    scripts/gen_design_tokens.py

Writes the Android Kotlin tokens and widget colours, and the iOS colour sets and Swift tokens.
Never edit the outputs by hand: change tokens.json and run this again.
"""
import json
import re
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOKENS = json.loads((ROOT / "docs/design/tokens.json").read_text())
ANDROID_KT = ROOT / "androidApp/src/main/java/com/foodtracker/android/ui/theme/LarderTokens.kt"
ANDROID_RES = ROOT / "androidApp/src/main/res"
IOS_COLORS = ROOT / "iosApp/FoodTracker/Assets.xcassets/Larder"
IOS_SWIFT = ROOT / "iosApp/FoodTracker/DesignSystem/LarderTokens.swift"
HEADER = "Generated by scripts/gen_design_tokens.py from docs/design/tokens.json. Do not edit."


def resolve(value):
    match = re.fullmatch(r"\{(\w+)\.(\w+)\}", value)
    if match:
        return TOKENS["primitives"]["color"][match[1]][match[2]]
    return value


def roles(theme):
    return {name: resolve(value).lower() for name, value in TOKENS["color"][theme].items()}


def camel(name):
    head, *rest = name.split("-")
    return head + "".join(part.capitalize() for part in rest)


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)


def android_kotlin():
    lines = [f"// {HEADER}", "package com.foodtracker.android.ui.theme", "",
             "import androidx.compose.ui.graphics.Color", "import androidx.compose.ui.unit.dp", "",
             "/** Every Larder colour role for one theme. */", "data class LarderColorRoles("]
    light, dark = roles("light"), roles("dark")
    lines += [f"    val {camel(name)}: Color," for name in light]
    lines += [")", ""]
    for label, palette in (("Light", light), ("Dark", dark)):
        lines.append(f"val Larder{label}Roles = LarderColorRoles(")
        lines += [f"    {camel(n)} = Color(0xFF{v[1:].upper()})," for n, v in palette.items()]
        lines += [")", ""]
    lines.append("object LarderSpace {")
    lines += [f"    val s{k} = {v}.dp" for k, v in TOKENS["space"].items()]
    lines += ["}", "", "object LarderRadius {"]
    lines += [f"    val {k} = {v}.dp" for k, v in TOKENS["radius"].items() if k != "full"]
    lines += ["}", "", "object LarderSize {"]
    lines += [f"    val {k} = {v}.dp" for k, v in TOKENS["size"].items()]
    lines += ["}", ""]
    write(ANDROID_KT, "\n".join(lines))


def android_widget_colors():
    for folder, theme in (("values", "light"), ("values-night", "dark")):
        items = "".join(f'    <color name="larder_{n.replace("-", "_")}">{v}</color>\n'
                        for n, v in roles(theme).items())
        write(ANDROID_RES / folder / "larder_colors.xml",
              f'<?xml version="1.0" encoding="utf-8"?>\n<!-- {HEADER} -->\n<resources>\n{items}</resources>\n')


def ios_color(value):
    return {"color-space": "srgb", "components": {
        "red": f"0x{value[1:3].upper()}", "green": f"0x{value[3:5].upper()}",
        "blue": f"0x{value[5:7].upper()}", "alpha": "1.000"}}


def ios_colors():
    shutil.rmtree(IOS_COLORS, ignore_errors=True)
    info = {"author": "xcode", "version": 1}
    write(IOS_COLORS / "Contents.json", json.dumps({"info": info, "properties": {"provides-namespace": True}}, indent=2) + "\n")
    light, dark = roles("light"), roles("dark")
    for name in light:
        contents = {"colors": [
            {"idiom": "universal", "color": ios_color(light[name])},
            {"idiom": "universal", "appearances": [{"appearance": "luminosity", "value": "dark"}],
             "color": ios_color(dark[name])}], "info": info}
        write(IOS_COLORS / f"{name}.colorset/Contents.json", json.dumps(contents, indent=2) + "\n")


def ios_swift():
    lines = [f"// {HEADER}", "import SwiftUI", "", "enum LarderColor {"]
    lines += [f'    static let {camel(n)} = Color("Larder/{n}")' for n in roles("light")]
    lines += ["}", "", "enum LarderSpace {"]
    lines += [f"    static let s{k}: CGFloat = {v}" for k, v in TOKENS["space"].items()]
    lines += ["}", "", "enum LarderRadius {"]
    lines += [f"    static let {k}: CGFloat = {v}" for k, v in TOKENS["radius"].items() if k != "full"]
    lines += ["}", "", "enum LarderSize {"]
    lines += [f"    static let {k}: CGFloat = {v}" for k, v in TOKENS["size"].items()]
    lines += ["}", ""]
    write(IOS_SWIFT, "\n".join(lines))


if __name__ == "__main__":
    android_kotlin()
    android_widget_colors()
    ios_colors()
    ios_swift()
